"""
fine_tune.py
-------------
QLoRA fine-tuning of Mistral-7B-Instruct on the tri-modal cyber attack
scenario dataset generated by generate_outputs.py.

What is QLoRA?
  Q  = Quantization: loads the model in 4-bit precision (uses ~4GB VRAM
       instead of ~28GB), making it runnable on a free Colab/Kaggle GPU.
  Lo = Low-Rank: instead of updating all 7 billion weights, we attach
       small "adapter" matrices (LoRA) to key layers and only train those.
  RA = Rank Adaptation: the adapters have rank r=16, meaning each adapter
       is a pair of tiny matrices (r x hidden_dim) — very few parameters.

Result: we get a fine-tuned model that knows cybersecurity scenario format
without needing a $10,000 GPU.

Usage (run from scenario_generation/):
    python fine_tuning/fine_tune.py \
        --data  dataset/training_data.jsonl \
        --out   fine_tuning/output/

Requirements:
    pip install -r fine_tuning/requirements_finetune.txt
"""

