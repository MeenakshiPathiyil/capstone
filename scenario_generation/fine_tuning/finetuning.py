"""
finetuning.py
-------------
QLoRA fine-tuning of Mistral-7B-Instruct on the tri-modal cyber attack
scenario dataset generated by generate_outputs.py.

What is QLoRA?
  Q  = Quantization: loads the model in 4-bit precision (uses ~4-5GB VRAM
       instead of ~28GB), making it runnable on a free Colab/Kaggle GPU.
  Lo = Low-Rank: instead of updating all 7 billion weights, we attach
       small "adapter" matrices (LoRA) to key layers and only train those.
  RA = Rank Adaptation: the adapters have rank r (default 16), meaning each
       adapter is a pair of tiny matrices (r x hidden_dim) — very few params.

Result: a fine-tuned model that knows the cybersecurity scenario format
without needing a $10,000 GPU.

Usage (run from scenario_generation/):
    python fine_tuning/fine_tune.py \
        --data  dataset/training_data.jsonl \
        --out   fine_tuning/output/

Offline probes (no GPU / no ML stack required):
    python fine_tuning/fine_tune.py --check_data        # split + token lengths
    python fine_tuning/fine_tune.py --smoke --out /tmp/s # 3-step CUDA-guarded run

Requirements:
    pip install -r fine_tuning/requirements_finetune.txt

Notes on portability:
  * The heavy ML imports (torch, transformers, trl, peft, datasets) are done
    LAZILY inside the functions that need them, so --help, --check_data and the
    GPU-less --smoke path work on a machine with no ML stack installed.
  * Written against the versions pinned in requirements_finetune.txt (TRL 0.29,
    transformers 5), the stack that trained the shipped adapter.
"""

import argparse
import math
import sys
from pathlib import Path

# Local shared modules (same directory). These are dependency-free so they import
# fine even without the ML stack.
import prompt_format
import data_split


# ── Constants ─────────────────────────────────────────────────────────────────

BASE_MODEL   = "mistralai/Mistral-7B-Instruct-v0.3"
MAX_SEQ_LEN  = 2048   # max token length per training example (see fix C)

# LoRA target-module presets.
ALL_LINEAR = ["q_proj", "k_proj", "v_proj", "o_proj", "gate_proj", "up_proj", "down_proj"]
ATTN_ONLY  = ["q_proj", "k_proj", "v_proj", "o_proj"]

# The three section headers the model must emit, in order (used by the self-test).
REQUIRED_HEADERS = ["[NATURAL LANGUAGE]", "[MATHEMATICAL EXPRESSION]", "[ATTACK GRAPH]"]


# ── Dependency check (only invoked on the real-training / GPU paths) ───────────

def check_imports():
    """Friendly check for the heavy ML stack; called only when we actually train."""
    missing = []
    for pkg, import_name in [
        ("transformers", "transformers"),
        ("peft",         "peft"),
        ("trl",          "trl"),
        ("bitsandbytes", "bitsandbytes"),
        ("datasets",     "datasets"),
        ("accelerate",   "accelerate"),
        ("torch",        "torch"),
    ]:
        try:
            __import__(import_name)
        except ImportError:
            missing.append(pkg)
    if missing:
        print("[!] Missing packages. Run:")
        print(f"    pip install {' '.join(missing)}")
        sys.exit(1)


# ── Dataset (shared split + the prompt the adapter was trained on) ────────────

def tokenize_example(tokenizer, record: dict) -> dict:
    """input_ids for prompt + answer, and a completion_mask that is 1 on the answer.

    Tokenized here rather than by TRL so the ids are exactly the ones inference
    sees: prompt_format embeds the <s>, so no special tokens are added, and the
    loss only falls on the answer.
    """
    prompt = prompt_format.build_prompt(record)
    prompt_ids = tokenizer(prompt, add_special_tokens=False)["input_ids"]
    input_ids = tokenizer(prompt + prompt_format.build_completion(record),
                          add_special_tokens=False)["input_ids"]
    if input_ids[:len(prompt_ids)] != prompt_ids:
        raise ValueError(f"{record['_meta']['source_id']}: the prompt does not tokenize "
                         "as a prefix of the full example")
    return {
        "input_ids": input_ids,
        "completion_mask": [0] * len(prompt_ids) + [1] * (len(input_ids) - len(prompt_ids)),
    }


def load_dataset_split(data_path, tokenizer, val_frac, seed):
    """Tokenized train and validation Datasets, plus the split they came from.

    The held-out test records are never trained on; see data_split.py.
    """
    from datasets import Dataset

    split = data_split.split(data_split.load_records(data_path), val_frac=val_frac, seed=seed)
    train_ds = Dataset.from_list([tokenize_example(tokenizer, r) for r in split["train"]])
    val_ds = Dataset.from_list([tokenize_example(tokenizer, r) for r in split["val"]])
    print(f"[+] Split: train {len(train_ds)} / val {len(val_ds)} / "
          f"test {len(split['test'])} (held out, never trained on)")
    return train_ds, val_ds, split


# ── Precision / hardware autodetect (fix D1) ──────────────────────────────────

def detect_bf16() -> bool:
    """True on GPUs that support bfloat16 (e.g. A100); False on T4 (fp16 only)."""
    import torch
    return torch.cuda.is_available() and torch.cuda.is_bf16_supported()


# ── Model + tokenizer loading (true QLoRA, fix D) ─────────────────────────────

def load_model_and_tokenizer(model_name: str, trust_remote_code: bool):
    """
    Load Mistral-7B in 4-bit quantized form (true QLoRA setup).

    BitsAndBytesConfig:
      - load_in_4bit              : compress base weights to 4-bit (~4-5GB VRAM)
      - bnb_4bit_quant_type="nf4" : NormalFloat4, best quality for 4-bit
      - bnb_4bit_use_double_quant : quantize the quantization constants too
      - bnb_4bit_compute_dtype    : bf16 on A100, fp16 on T4 — MATCHED to the
                                    mixed-precision used by the trainer (fix D1).
    We do NOT set bnb_4bit_quant_storage (default uint8) and never use fp32
    compute (fixes D2). After loading we run prepare_model_for_kbit_training so
    LoRA trains correctly on the quantized base (fix D4).
    """
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
    from peft import prepare_model_for_kbit_training

    bf16 = detect_bf16()
    compute_dtype = torch.bfloat16 if bf16 else torch.float16
    print(f"[+] Precision: {'bf16' if bf16 else 'fp16'} "
          f"(compute_dtype={compute_dtype})")

    print(f"[+] Loading base model: {model_name}")
    print("    This downloads ~14GB on first run. Subsequent runs use cache.")

    bnb_config = BitsAndBytesConfig(
        load_in_4bit=True,
        bnb_4bit_quant_type="nf4",
        bnb_4bit_use_double_quant=True,
        bnb_4bit_compute_dtype=compute_dtype,
    )

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        quantization_config=bnb_config,
        device_map="auto",                 # places layers on GPU automatically
        trust_remote_code=trust_remote_code,
    )

    model.config.use_cache = False         # required for gradient checkpointing
    model.config.pretraining_tp = 1

    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=trust_remote_code)
    # Mistral has no pad token by default; reuse EOS so batches can pad.
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "right"       # right padding for causal-LM training

    # k-bit prep: upcasts layernorms to fp32, enables input grads, and turns on
    # gradient checkpointing — must run AFTER the 4-bit load and BEFORE LoRA.
    model = prepare_model_for_kbit_training(model, use_gradient_checkpointing=True)

    print("[+] Model loaded and prepared for k-bit training")
    return model, tokenizer, bf16


# ── LoRA config (fix G2: target modules configurable) ─────────────────────────

def attach_lora(model, r, alpha, dropout, target_modules):
    """
    Attach LoRA adapter matrices. Only A/B adapter weights train; the 4-bit base
    is frozen. By default we adapt ALL linear projections (attention + MLP), which
    generally fits a new output format better than attention-only.
    """
    from peft import LoraConfig, get_peft_model, TaskType

    lora_config = LoraConfig(
        r=r,
        lora_alpha=alpha,
        target_modules=target_modules,
        lora_dropout=dropout,
        bias="none",
        task_type=TaskType.CAUSAL_LM,
    )
    model = get_peft_model(model, lora_config)

    trainable, total = model.get_nb_trainable_parameters()
    print("[+] LoRA adapters attached")
    print(f"    Target modules   : {target_modules}")
    print(f"    Trainable params : {trainable:,}  ({100 * trainable / total:.2f}% of total)")
    print(f"    Total params     : {total:,}")
    return model


# ── SFTConfig (TRL 0.29, as pinned in requirements_finetune.txt) ─────────────

def build_sft_config(output_dir, args, bf16, eval_mode="epoch", max_steps=None):
    """The training config. eval_mode: "epoch" (full run), "steps" (smoke) or "no"."""
    from trl import SFTConfig

    kwargs = dict(
        output_dir=output_dir,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=args.grad_accum,
        optim="paged_adamw_8bit",
        learning_rate=args.lr,
        lr_scheduler_type="cosine",
        warmup_steps=5,
        bf16=bf16,
        fp16=not bf16,
        logging_steps=2 if max_steps else 10,
        save_total_limit=2,
        report_to="none",
        max_length=args.max_seq_len,
        completion_only_loss=True,
        packing=False,
        max_grad_norm=0.3,
        gradient_checkpointing=True,
        gradient_checkpointing_kwargs={"use_reentrant": False},
        seed=args.seed,
        data_seed=args.seed,
    )
    if max_steps is not None:
        kwargs["max_steps"] = max_steps
    else:
        kwargs["num_train_epochs"] = args.epochs

    if eval_mode == "no":
        kwargs.update(eval_strategy="no", save_strategy="no")
    else:
        if eval_mode == "steps":
            kwargs.update(eval_strategy="steps", eval_steps=2, save_strategy="steps", save_steps=2)
        else:
            kwargs.update(eval_strategy="epoch", save_strategy="epoch")
        kwargs.update(per_device_eval_batch_size=1, load_best_model_at_end=True,
                      metric_for_best_model="eval_loss", greater_is_better=False)

    return SFTConfig(**kwargs)


# ── Trainer ───────────────────────────────────────────────────────────────────

def build_trainer(model, tokenizer, sft_config, train_ds, eval_ds):
    from trl import SFTTrainer
    from transformers import EarlyStoppingCallback

    kwargs = dict(model=model, args=sft_config, train_dataset=train_ds,
                  processing_class=tokenizer)
    if eval_ds is not None:
        kwargs["eval_dataset"] = eval_ds
        kwargs["callbacks"] = [EarlyStoppingCallback(early_stopping_patience=2)]
    return SFTTrainer(**kwargs)


# ── Post-training self-test (fix P3) ──────────────────────────────────────────

def post_training_selftest(model, tokenizer, test_rec, max_new_tokens):
    """
    Generate one held-out sample and assert (i) all three headers present in
    order and (ii) EOS reached before max_new_tokens. Prints PASS/FAIL.
    """
    import torch

    model.config.use_cache = True
    if hasattr(model, "gradient_checkpointing_disable"):
        model.gradient_checkpointing_disable()
    model.eval()

    prompt = prompt_format.build_prompt(test_rec)
    inputs = tokenizer(prompt, return_tensors="pt", add_special_tokens=False).to(model.device)
    n = inputs["input_ids"].shape[1]
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            eos_token_id=tokenizer.eos_token_id,
            pad_token_id=tokenizer.pad_token_id,
        )
    new_ids = out[0][n:].tolist()
    text = tokenizer.decode(new_ids, skip_special_tokens=True)

    positions = [text.find(h) for h in REQUIRED_HEADERS]
    headers_ok = all(p >= 0 for p in positions) and positions == sorted(positions)
    eos_hit = tokenizer.eos_token_id in new_ids

    print()
    print("─" * 60)
    print("[self-test] held-out generation")
    print(f"    headers present & in order : {headers_ok}  ({positions})")
    print(f"    EOS reached before cap     : {eos_hit}  "
          f"(generated {len(new_ids)}/{max_new_tokens} tokens)")
    ok = headers_ok and eos_hit
    print(f"    RESULT: {'PASS' if ok else 'FAIL'}")
    print("─" * 60)
    return ok


# ── Optional adapter merge (fix P4) ───────────────────────────────────────────

def merge_adapter(base_model, adapter_dir, out_dir, trust_remote_code):
    """
    Merge the LoRA adapter into a fresh fp16 copy of the base model and save it
    alongside the adapter. NOTE: this loads the FULL (non-quantized) base in
    fp16, so it needs ~14-16GB of RAM/VRAM — far more than 4-bit training.
    """
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from peft import PeftModel

    print("[+] --merge: loading base in fp16 to merge the adapter "
          "(needs ~14-16GB; off by default)…")
    base = AutoModelForCausalLM.from_pretrained(
        base_model, torch_dtype=torch.float16, device_map="auto",
        trust_remote_code=trust_remote_code,
    )
    merged = PeftModel.from_pretrained(base, adapter_dir)
    merged = merged.merge_and_unload()
    mdir = Path(out_dir) / "merged"
    merged.save_pretrained(mdir, safe_serialization=True)
    AutoTokenizer.from_pretrained(base_model, trust_remote_code=trust_remote_code).save_pretrained(mdir)
    print(f"[✓] Merged fp16 model saved to: {mdir}")


# ── Training orchestration ────────────────────────────────────────────────────

def masked_prompt_tokens(example) -> int:
    """How many leading tokens of a tokenized example carry no loss."""
    return example["completion_mask"].index(1)


def train(args):
    """Run the supervised fine-tuning loop, with loss on the answer only."""
    check_imports()
    from transformers import set_seed
    set_seed(args.seed)

    model, tokenizer, bf16 = load_model_and_tokenizer(args.base, args.trust_remote_code)
    model = attach_lora(model, args.r, args.alpha, args.lora_dropout, args.target_modules)

    train_ds, val_ds, split = load_dataset_split(args.data, tokenizer, args.val_frac, args.seed)
    too_long = [len(ids) for ids in train_ds["input_ids"] + val_ds["input_ids"]
                if len(ids) > args.max_seq_len]
    if too_long:
        print(f"[!] {len(too_long)} examples exceed max_length={args.max_seq_len} "
              f"(longest {max(too_long)}). Truncating them would cut off the end of the "
              "answer and its </s>; raise --max_seq_len.")
        sys.exit(1)

    eff_batch = args.batch_size * args.grad_accum
    steps_per_epoch = math.ceil(len(train_ds) / eff_batch)
    print()
    print("[+] Starting training…")
    print(f"    Output dir       : {args.out}")
    print(f"    Epochs           : {args.epochs}")
    print(f"    Effective batch  : {eff_batch} (bs {args.batch_size} x accum {args.grad_accum})")
    print(f"    Optimizer steps  : ~{steps_per_epoch * args.epochs} "
          f"({steps_per_epoch}/epoch x {args.epochs})")
    print(f"    Prompt tokens without loss (first example): {masked_prompt_tokens(train_ds[0])}")
    print()

    trainer = build_trainer(model, tokenizer, build_sft_config(args.out, args, bf16),
                            train_ds, val_ds)
    trainer.train()
    print(f"[+] Best checkpoint: {trainer.state.best_model_checkpoint}  "
          f"(eval_loss={trainer.state.best_metric})")

    print("[+] Saving final adapter weights…")
    trainer.save_model(args.out)
    tokenizer.save_pretrained(args.out)
    print(f"[✓] Model saved to: {args.out}")

    ok = post_training_selftest(model, tokenizer, split["test"][0], args.max_new_tokens)

    if args.merge:
        merge_adapter(args.base, args.out, args.out, args.trust_remote_code)

    print()
    print("Next step: run evaluation/judge_eval.py to score the fine-tuned model")
    if not ok:
        sys.exit(1)


# ── --check_data probe (no model load) ────────────────────────────────────────

def run_check_data(args) -> int:
    print("=" * 60)
    print("  --check_data : data, split and token-length probe (no model load)")
    print("=" * 60)

    if not Path(args.data).exists():
        print(f"[!] Dataset not found: {args.data}")
        return 1

    split = data_split.split(data_split.load_records(args.data),
                             val_frac=args.val_frac, seed=args.seed)
    print(f"[+] Split: train {len(split['train'])} / val {len(split['val'])} / "
          f"test {len(split['test'])}")

    try:
        from transformers import AutoTokenizer
        tokenizer = AutoTokenizer.from_pretrained(args.base, trust_remote_code=args.trust_remote_code)
    except Exception as e:
        print(f"[i] Tokenizer unavailable ({type(e).__name__}); token checks skipped.")
        print("\n[✓] check_data: split OK")
        return 0

    examples = [tokenize_example(tokenizer, r) for r in split["train"] + split["val"]]
    lengths = sorted(len(e["input_ids"]) for e in examples)
    print(f"[+] Training example length in tokens: min={lengths[0]} "
          f"median={lengths[len(lengths) // 2]} max={lengths[-1]}")
    print(f"[+] Prompt tokens without loss (first example): {masked_prompt_tokens(examples[0])}")

    over = sum(1 for n in lengths if n > args.max_seq_len)
    if over:
        print(f"[!] {over} example(s) exceed max_length={args.max_seq_len}. "
              "Raise --max_seq_len before training.")
        return 1

    print("\n[✓] check_data: ALL CHECKS PASSED")
    return 0


# ── --smoke probe (CUDA-guarded) ──────────────────────────────────────────────

def run_smoke(args) -> int:
    print("=" * 60)
    print("  --smoke : 3-step end-to-end training + 1 generation")
    print("=" * 60)
    try:
        import torch
    except ImportError:
        torch = None
    if torch is None or not torch.cuda.is_available():
        print("[smoke] No CUDA GPU here, so smoke is a NO-OP.")
        print("        On Colab with a GPU this runs max_steps=3 training + one")
        print("        generation to exercise the whole path fast.")
        return 0

    check_imports()
    from transformers import set_seed
    set_seed(args.seed)

    model, tokenizer, bf16 = load_model_and_tokenizer(args.base, args.trust_remote_code)
    model = attach_lora(model, args.r, args.alpha, args.lora_dropout, args.target_modules)
    train_ds, val_ds, split = load_dataset_split(args.data, tokenizer, args.val_frac, args.seed)

    sft_config = build_sft_config(args.out, args, bf16, eval_mode="steps", max_steps=3)
    trainer = build_trainer(model, tokenizer, sft_config, train_ds, val_ds)
    trainer.train()
    print(f"[smoke] best checkpoint: {trainer.state.best_model_checkpoint} "
          f"(eval_loss={trainer.state.best_metric})")

    post_training_selftest(model, tokenizer, split["test"][0],
                           max_new_tokens=min(args.max_new_tokens, 256))
    print("[✓] smoke complete")
    return 0


# ── target-module parsing (fix G2) ────────────────────────────────────────────

def parse_target_modules(value: str):
    if value == "all":
        return ALL_LINEAR
    if value == "attn":
        return ATTN_ONLY
    return [m.strip() for m in value.split(",") if m.strip()]


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="QLoRA fine-tuning for scenario generation")
    parser.add_argument("--data", default="dataset/training_data.jsonl",
                        help="Path to training_data.jsonl")
    parser.add_argument("--out", default="fine_tuning/output",
                        help="Output directory for adapter weights")
    parser.add_argument("--base", default=BASE_MODEL, help=f"Base model (default: {BASE_MODEL})")

    # Hyperparameters (fix G5) — current values as defaults.
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--lr", type=float, default=2e-4)
    parser.add_argument("--r", type=int, default=16, help="LoRA rank")
    parser.add_argument("--alpha", type=int, default=32, help="LoRA alpha")
    parser.add_argument("--lora_dropout", type=float, default=0.05)
    parser.add_argument("--max_seq_len", type=int, default=MAX_SEQ_LEN)
    parser.add_argument("--target_modules", default="all",
                        help='"all" (default, all linear), "attn" (attention-only), '
                             "or a comma list e.g. q_proj,v_proj")
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--grad_accum", type=int, default=4)

    # Split / reproducibility. The test set is fixed; see data_split.py.
    parser.add_argument("--val_frac", type=float, default=0.15,
                        help="Validation fraction of the train pool")
    parser.add_argument("--seed", type=int, default=42)

    # Behaviour flags.
    parser.add_argument("--trust_remote_code", action="store_true",
                        help="Pass trust_remote_code=True (unnecessary for Mistral)")
    parser.add_argument("--max_new_tokens", type=int, default=1280,
                        help="Tokens to generate in the post-training self-test")
    parser.add_argument("--merge", action="store_true",
                        help="Also save a merged fp16 model (needs ~14-16GB)")
    parser.add_argument("--check_data", action="store_true",
                        help="Offline data + prompt-parity probe (no model load)")
    parser.add_argument("--smoke", action="store_true",
                        help="3-step CUDA-guarded end-to-end run (no-op without a GPU)")

    args = parser.parse_args()
    args.target_modules = parse_target_modules(args.target_modules)

    # Offline probes first (these never load the 7B model unless a GPU is present).
    if args.check_data:
        sys.exit(run_check_data(args))
    if args.smoke:
        sys.exit(run_smoke(args))

    # ── Real training path ──
    check_imports()                      # friendly message if the ML stack is absent
    import torch
    if not torch.cuda.is_available():
        print("[!] WARNING: No GPU detected.")
        print("    QLoRA fine-tuning needs a GPU with >=16GB VRAM (Colab T4 / Kaggle).")
        print("    Continuing anyway — will be extremely slow on CPU.")
        print()

    print("=" * 60)
    print("  QLoRA Fine-Tuning — Cyber Attack Scenario Generation")
    print("=" * 60)
    print(f"  Base model : {args.base}")
    print(f"  Dataset    : {args.data}")
    print(f"  Output     : {args.out}")
    print("=" * 60)
    print()

    if not Path(args.data).exists():
        print(f"[!] Dataset not found: {args.data}")
        print("    Run generate_outputs.py first.")
        sys.exit(1)

    Path(args.out).mkdir(parents=True, exist_ok=True)
    train(args)


if __name__ == "__main__":
    main()
