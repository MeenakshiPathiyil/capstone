check_imports()

import torch
from datasets import Dataset
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
from peft import LoraConfig, get_peft_model, TaskType
from trl import SFTTrainer, SFTConfig


# ── Constants ─────────────────────────────────────────────────────────────────

BASE_MODEL   = "mistralai/Mistral-7B-Instruct-v0.3"
MAX_SEQ_LEN  = 2048   # max token length per training example


# ── Dataset loading ───────────────────────────────────────────────────────────

def load_training_data(jsonl_path: str) -> Dataset:
    """
    Load training_data.jsonl and format each record into a single
    'text' field that the trainer expects.

    Format used: Alpaca-style instruction tuning prompt.
    The model learns: given (instruction + input), produce output.
    """
    records = []
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue

            # Skip records that are missing critical fields
            if not rec.get("output") or not rec.get("input"):
                continue

            # Build the full training text in Alpaca instruction format.
            # This is exactly what the model sees during training.
            # [INST] ... [/INST] is Mistral's special chat template.
            instruction = rec.get("instruction", "")
            text = (
                f"[INST] {instruction}\n\n"
                f"{rec['input']} [/INST]\n"
                f"{rec['output']}"
            )
            records.append({"text": text})

    if not records:
        print("[!] No valid records found in the dataset file.")
        sys.exit(1)

    print(f"[+] Loaded {len(records)} training records")
    dataset = Dataset.from_list(records)

    # 80/20 train/validation split
    split = dataset.train_test_split(test_size=0.2, seed=42)
    print(f"    Train : {len(split['train'])} examples")
    print(f"    Val   : {len(split['test'])}  examples")
    return split


# ── Model loading ─────────────────────────────────────────────────────────────

def load_model_and_tokenizer(model_name: str):
    """
    Load Mistral-7B in 4-bit quantized form (QLoRA setup).

    BitsAndBytesConfig tells the loader:
      - load_in_4bit: compress weights to 4-bit (saves ~24GB of VRAM)
      - bnb_4bit_quant_type="nf4": NormalFloat4, best quality for 4-bit
      - bnb_4bit_use_double_quant: quantize the quantization constants too
        (saves another ~0.4 bits per parameter)
      - bnb_4bit_compute_dtype=float16: do actual math in float16 for speed
    """
    print(f"[+] Loading base model: {model_name}")
    print(f"    This downloads ~14GB on first run. Subsequent runs use cache.")

    bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_use_double_quant=True,
    bnb_4bit_compute_dtype=torch.float32,
    bnb_4bit_quant_storage=torch.float32,
)

    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        quantization_config=bnb_config,
        device_map="auto",          # automatically puts layers on GPU/CPU
        trust_remote_code=True,
    )

    # Required for gradient checkpointing to work with quantized models
    model.config.use_cache = False
    model.config.pretraining_tp = 1

    tokenizer = AutoTokenizer.from_pretrained(model_name, trust_remote_code=True)

    # Mistral tokenizer doesn't have a pad token by default.
    # We set it to eos_token so the tokenizer can pad batches.
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "right"   # pad on right for causal LM training

    print(f"[+] Model loaded successfully")
    return model, tokenizer


# ── LoRA config ───────────────────────────────────────────────────────────────

def attach_lora(model):
    """
    Attach LoRA adapter matrices to the model.

    Instead of fine-tuning all 7B parameters, LoRA inserts two small
    matrices (A and B) into specific layers. During training, only A and B
    are updated. At inference, we compute: W + A*B (original + adapter).

    Parameters:
      r=16            : rank of the adapter matrices. Higher = more capacity
                        but more memory. 16 is a good balance for this task.
      lora_alpha=32   : scaling factor. Convention is alpha = 2*r.
      target_modules  : which attention layers to adapt. q_proj and v_proj
                        are the query and value projection matrices in
                        Mistral's attention mechanism — adapting these gives
                        the best results for instruction-following tasks.
      lora_dropout    : dropout rate on adapter layers to prevent overfitting.
      bias="none"     : don't train bias terms (saves parameters).
    """
    lora_config = LoraConfig(
        r=16,
        lora_alpha=32,
        target_modules=["q_proj", "v_proj", "k_proj", "o_proj"],
        lora_dropout=0.05,
        bias="none",
        task_type=TaskType.CAUSAL_LM,
    )

    model = get_peft_model(model, lora_config)

    # Print how many parameters we're actually training vs total
    trainable, total = model.get_nb_trainable_parameters()
    print(f"[+] LoRA adapters attached")
    print(f"    Trainable params : {trainable:,}  ({100 * trainable / total:.2f}% of total)")
    print(f"    Total params     : {total:,}")
    print(f"    (Training only the adapter weights, not the full model)")

    return model


# ── Training ──────────────────────────────────────────────────────────────────

def train(model, tokenizer, dataset_split, output_dir: str):
    import os
    os.environ["ACCELERATE_MIXED_PRECISION"] = "fp16"
    """
    Run the supervised fine-tuning loop using SFTTrainer.

    SFTTrainer (from the trl library) is a wrapper around HuggingFace's
    Trainer that handles:
      - tokenizing the text field automatically
      - packing short examples together to fill the context window
      - masking the instruction part so loss is only on the output

    Key training arguments:
      num_train_epochs=3 : pass over the data 3 times
      per_device_train_batch_size=1 : one example per GPU step (our dataset
                                      is small, gradient_accumulation compensates)
      gradient_accumulation_steps=4 : accumulate 4 steps before updating
                                      weights → effective batch size = 4
      learning_rate=2e-4 : standard for LoRA fine-tuning
      fp16=True          : mixed precision training (faster on GPU)
      save_steps=25      : save a checkpoint every 25 steps
      logging_steps=10   : print loss every 10 steps
    """
    sft_config = SFTConfig(
    output_dir=output_dir,
    num_train_epochs=3,
    per_device_train_batch_size=1,
    gradient_accumulation_steps=4,
    optim="adamw_torch",
    learning_rate=2e-4,
    lr_scheduler_type="cosine",
    warmup_steps=5,
    fp16=False,          # turn off entirely
    bf16=False,          # turn off entirely
    logging_steps=10,
    save_steps=25,
    save_total_limit=2,
    report_to="none",
    dataset_text_field="text",
    packing=False,
    max_grad_norm=0.3,
    )

    # TRL changed this parameter name across versions.
    # Support both to avoid runtime failures on Colab.
    try:
        trainer = SFTTrainer(
            model=model,
            tokenizer=tokenizer,
            train_dataset=dataset_split["train"],
            eval_dataset=dataset_split["test"],
            args=sft_config,
        )
    except TypeError:
        trainer = SFTTrainer(
            model=model,
            processing_class=tokenizer,
            train_dataset=dataset_split["train"],
            eval_dataset=dataset_split["test"],
            args=sft_config,
        )

    print()
    print("[+] Starting training...")
    print(f"    Output dir : {output_dir}")
    print(f"    Epochs     : 3")
    print(f"    Steps      : ~{len(dataset_split['train']) * 3} total")
    print()

    trainer.train()

    print()
    print("[+] Training complete. Saving final adapter weights...")
    trainer.save_model(output_dir)
    tokenizer.save_pretrained(output_dir)
    print(f"[✓] Model saved to: {output_dir}")
    print()
    print("Next step: run evaluation/evaluate.py to score the fine-tuned model")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="QLoRA fine-tuning for scenario generation")
    parser.add_argument("--data", required=True,  help="Path to training_data.jsonl")
    parser.add_argument("--out",  required=True,  help="Output directory for adapter weights")
    parser.add_argument("--base", default=BASE_MODEL, help=f"Base model (default: {BASE_MODEL})")
    args = parser.parse_args()

    # ── GPU check ──
    if not torch.cuda.is_available():
        print("[!] WARNING: No GPU detected.")
        print("    QLoRA fine-tuning requires a GPU with at least 16GB VRAM.")
        print("    Use Google Colab (free T4) or Kaggle (free P100) if you don't have one locally.")
        print("    Continuing anyway — will be extremely slow on CPU.")
        print()

    print("=" * 60)
    print("  QLoRA Fine-Tuning — Cyber Attack Scenario Generation")
    print("=" * 60)
    print(f"  Base model : {args.base}")
    print(f"  Dataset    : {args.data}")
    print(f"  Output     : {args.out}")
    print("=" * 60)
    print()

    # Check dataset exists
    if not Path(args.data).exists():
        print(f"[!] Dataset not found: {args.data}")
        print("    Run generate_outputs.py first.")
        sys.exit(1)

    # Create output dir
    Path(args.out).mkdir(parents=True, exist_ok=True)

    # Run pipeline
    dataset_split         = load_training_data(args.data)
    model, tokenizer      = load_model_and_tokenizer(args.base)
    model                 = attach_lora(model)
    train(model, tokenizer, dataset_split, args.out)


if __name__ == "__main__":
    main()