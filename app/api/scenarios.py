"""Scenario generation for exported attack paths: the job service and its routes.

One FIFO worker task runs live generations against the model Space, one at a
time, with at most `scenario_queue_max` jobs waiting behind it. Jobs live in
memory only: after a restart an unfinished job is simply idle again, and the
local cache (scenario_cache.py) keeps every finished result.

Per path the state is, in order of precedence:
    an active job        queued / warming_up / running
    a failed last job    failed (until an explicit POST starts a new one)
    a finished job       done (generated by this process for this path)
    a cached entry       cached (linked to the path, or under its current key)
    nothing              idle

Every Space response is checked with scenario_contract.validate_result against
the provenance it was requested with before it is cached; a mismatch fails the
job and is never relabelled. Nothing here runs at import time.
"""

from __future__ import annotations

import asyncio
import logging
import time
from collections import deque
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Callable

from fastapi import APIRouter, Request, Response

from app.api import scenario_cache as cache
from app.api import scenario_contract as contract
from app.api import schemas
from app.api.config import Settings
from app.api.rate_limit import admission
from app.api.space_client import (
    RUNNING_STAGES,
    GenerationTimeout,
    Quota,
    SpaceClient,
    SpaceError,
    create_space_client,
    stage_problem
)
from app.api.worker import JobError


log = logging.getLogger(__name__)

NOT_EXPORTED = (
    "Scenarios are generated only for paths at or above the analysis's minimum level."
)


@dataclass
class Job:
    """One live generation, shared by every path whose prompt has its key."""

    key: str
    prompt: str
    prompt_version: str
    provenance: dict[str, Any]
    targets: list[tuple[str, str]]
    status: str = "queued"
    created: float = field(default_factory=time.monotonic)
    started: float | None = None

    def elapsed_s(self) -> float:
        return round(time.monotonic() - (self.started or self.created), 1)


@dataclass
class SpaceStatus:
    """What /api/health reports about the Space, refreshed at most once a TTL."""

    stage: str | None = None
    quota: Quota = field(default_factory=Quota)
    checked: float | None = None
    # When `stage` was last read or seen (monotonic); None while it is unknown.
    stage_at: float | None = None


class ScenarioService:
    """The scenario worker, its in-memory jobs and the cache it fills."""

    def __init__(
        self,
        settings: Settings,
        analyses,
        space_factory: Callable[[Settings], SpaceClient] | None = None
    ):
        self.settings = settings
        self.analyses = analyses
        # Tests pass a factory over fake clients; nothing in Settings can.
        self._space_factory = space_factory or create_space_client

        self.space: SpaceClient | None = None
        self.provenance: dict[str, Any] | None = None
        self.config_problem: str | None = None

        self.jobs: dict[str, Job] = {}
        self.by_path: dict[tuple[str, str], Job] = {}
        self.failed: dict[tuple[str, str], str] = {}
        self.finished: dict[tuple[str, str], str] = {}
        self.pending: deque[Job] = deque()
        self.current: Job | None = None
        self.status = SpaceStatus()

        self._records: dict[str, dict[str, tuple[bool, dict | None]]] = {}
        self._lock: asyncio.Lock | None = None
        self._wake: asyncio.Event | None = None
        self._worker: asyncio.Task | None = None
        self._refresh: asyncio.Task | None = None

    # -- Lifecycle ---------------------------------------------------------------

    async def start(self) -> None:
        """Read the live configuration and start the worker. No network here."""

        self._lock = asyncio.Lock()
        self._wake = asyncio.Event()

        self.config_problem = self.settings.live_config_problem()

        if self.config_problem is None:
            try:
                self.provenance = self.settings.scenario_provenance()
                self.space = self._space_factory(self.settings)

            except ImportError as error:
                self.config_problem = (
                    "Live scenario generation needs gradio_client and huggingface_hub "
                    "(app/api/requirements.txt): %s." % error.name
                )

        if self.config_problem:
            log.info("Live scenario generation is off. %s", self.config_problem)

        self._worker = asyncio.create_task(self._work(), name="scenario-worker")

    async def stop(self) -> None:
        """Cancel the worker (and a running job's remote request) and the refresh."""

        for task in (self._worker, self._refresh):
            if task is not None and not task.done():
                task.cancel()

        for task in (self._worker, self._refresh):
            if task is not None:
                try:
                    await task

                except (asyncio.CancelledError, Exception):
                    pass

        self._worker = self._refresh = None

    # -- Paths -------------------------------------------------------------------

    async def _path(self, analysis_id: str, source_id: str) -> dict[str, str]:
        """The path's seven-key export record. 404 unknown, 409 not exported."""

        records = self._records.get(analysis_id)

        if records is None:
            analysis = await self.analyses.get(analysis_id)

            records = {
                path["source_id"]: (bool(path["exported"]), path.get("export"))
                for path in analysis["paths"]
            }

            self._records[analysis_id] = records

        if source_id not in records:
            raise JobError(404, "Path %s is not in this analysis." % source_id)

        exported, record = records[source_id]

        if not exported or not record:
            raise JobError(409, NOT_EXPORTED)

        return record

    def _linked(self, analysis_id: str, source_id: str, record: dict[str, str]):
        """(entry, error): the entry linked to the path, or why it is unreadable.

        A link to an entry made from a different prompt than this path's current
        record is ignored: the path reads as if it had no link. The prompt is
        rebuilt in the entry's own format, so changing SCENARIO_PROMPT_FORMAT
        never hides or relabels an earlier result.
        """

        root = self.settings.cache_dir

        try:
            key = cache.read_links(root, analysis_id).get(source_id)

            if key is None:
                return None, None

            entry = cache.read_entry(root, key)

        except cache.CacheError as error:
            return None, "The saved scenario could not be read: %s" % error

        if entry is None:
            return None, "The saved scenario %s is missing from the cache." % key[:12]

        if not cache.entry_matches(entry, record):
            return None, None

        return entry, None

    def _current_key(self, record: dict[str, str]) -> tuple[str, str] | None:
        """(prompt, cache key) under the live configuration, None when it is off.

        The prompt is built in the configured SCENARIO_PROMPT_FORMAT and the key
        carries that format's prompt_version.
        """

        if self.provenance is None:
            return None

        try:
            prompt = contract.build_prompt(record, self.settings.scenario_prompt_format)

        except contract.ScenarioContractError as error:
            raise JobError(
                409, "This path's export record cannot be turned into a prompt: %s" % error
            ) from None

        return prompt, contract.cache_key(prompt, self.provenance, self.settings.prompt_version)

    # -- States ------------------------------------------------------------------

    def _job_state(self, job: Job) -> dict[str, Any]:

        position = None

        if job.status == "queued":
            ahead = list(self.pending).index(job) if job in self.pending else 0
            position = ahead + (1 if self.current is not None else 0)

        return {
            "status": job.status,
            "queue_position": position,
            "elapsed_s": job.elapsed_s(),
            "eta_s": None,
            "scenario": None,
            "error": None
        }

    @staticmethod
    def _state(status, scenario=None, error=None) -> dict[str, Any]:
        return {
            "status": status,
            "queue_position": None,
            "elapsed_s": None,
            "eta_s": None,
            "scenario": scenario,
            "error": error
        }

    def _read_state(
        self, analysis_id: str, source_id: str, record
    ) -> tuple[dict[str, Any], str | None]:
        """(state, key): the path's state, and the cache key of a hit found only
        under the live configuration (not yet linked), else None. No side
        effects. Callers hold the lock."""

        target = (analysis_id, source_id)

        job = self.by_path.get(target)

        if job is not None:
            return self._job_state(job), None

        entry, cache_error = self._linked(analysis_id, source_id, record)

        if target in self.failed:
            payload = contract.scenario_payload(entry) if entry else None
            return self._state("failed", payload, self.failed[target]), None

        if entry is not None:
            status = "done" if self.finished.get(target) == entry["cache_key"] else "cached"
            return self._state(status, contract.scenario_payload(entry)), None

        current = self._current_key(record)

        if current is not None:
            try:
                entry = cache.read_entry(self.settings.cache_dir, current[1])

            except cache.CacheError as error:
                cache_error = cache_error or "The saved scenario could not be read: %s" % error

            if entry is not None:
                return self._state("cached", contract.scenario_payload(entry)), current[1]

        if cache_error:
            return self._state("failed", None, cache_error), None

        return self._state("idle"), None

    async def get(self, analysis_id: str, source_id: str) -> dict[str, Any]:
        """GET: the path's state; idle when nothing was ever requested."""

        record = await self._path(analysis_id, source_id)

        async with self._lock:
            state, unlinked = self._read_state(analysis_id, source_id, record)

            # Link what is served, so the report (which includes only linked
            # scenarios) shows it and it outlives a change of configuration.
            if unlinked is not None:
                await asyncio.to_thread(
                    cache.link, self.settings.cache_dir, analysis_id, source_id, unlinked,
                    replace=True
                )

            return state

    @staticmethod
    def _unavailable(reason: str, retry_after_s: int | None = None) -> JobError:
        """503. Retry-After only when waiting can help; a permanent condition
        (not configured, Space paused or broken) carries none."""

        headers = {} if retry_after_s is None else {"Retry-After": str(max(retry_after_s, 1))}

        return JobError(503, reason, headers)

    def _known_stage_problem(self) -> str | None:
        """The setup message for the Space's last known stage, when that stage
        is recent and one the Space cannot serve from. Reads the cached snapshot
        only; a stale or unknown stage never blocks, the worker decides."""

        status = self.status

        if status.stage is None or status.stage_at is None:
            return None

        if time.monotonic() - status.stage_at >= self.settings.space_status_ttl_s:
            return None

        return stage_problem(status.stage)

    async def request(
        self,
        analysis_id: str,
        source_id: str,
        admit: Callable[[], None] | None = None
    ) -> tuple[int, dict[str, Any]]:
        """POST: (200, cached state) or (202, active job state), else JobError.

        admit (a rate limit) is called only when a new live job is about to be
        queued; serving a cached result or joining a job costs nothing.
        """

        record = await self._path(analysis_id, source_id)
        target = (analysis_id, source_id)

        async with self._lock:

            job = self.by_path.get(target)

            if job is not None:
                return 202, self._job_state(job)

            entry, _ = self._linked(analysis_id, source_id, record)

            if entry is not None:
                self.failed.pop(target, None)
                status = "done" if self.finished.get(target) == entry["cache_key"] else "cached"
                return 200, self._state(status, contract.scenario_payload(entry))

            if self.config_problem or self.space is None:
                raise self._unavailable(self.config_problem or "Live generation is off.")

            prompt, key = self._current_key(record)

            try:
                entry = cache.read_entry(self.settings.cache_dir, key)

            except cache.CacheError as error:
                log.warning("Unreadable scenario cache entry, regenerating: %s", error)
                entry = None

            if entry is not None:
                await asyncio.to_thread(
                    cache.link, self.settings.cache_dir, analysis_id, source_id, key,
                    replace=True
                )
                self.failed.pop(target, None)
                return 200, self._state("cached", contract.scenario_payload(entry))

            job = self.jobs.get(key)

            if job is not None:
                job.targets.append(target)
                self.by_path[target] = job
                self.failed.pop(target, None)
                return 202, self._job_state(job)

            problem = self._known_stage_problem()

            if problem:
                raise self._unavailable(problem)

            quota = self.status.quota

            if quota.exhausted():
                retry = self.settings.scenario_retry_after_s

                if quota.resets_at is not None:
                    retry = max(int((quota.resets_at - datetime.now(timezone.utc))
                                    .total_seconds()), 1)

                raise self._unavailable(quota_message(quota), retry)

            if len(self.pending) >= self.settings.scenario_queue_max:
                raise self._unavailable(
                    "The scenario queue is full (%d waiting). Try again shortly."
                    % len(self.pending),
                    self.settings.scenario_retry_after_s
                )

            if admit is not None:
                admit()

            job = Job(
                key=key,
                prompt=prompt,
                prompt_version=self.settings.prompt_version,
                provenance=self.provenance,
                targets=[target]
            )

            self.jobs[key] = job
            self.by_path[target] = job
            self.failed.pop(target, None)
            self.finished.pop(target, None)
            self.pending.append(job)
            self._wake.set()

            log.info("Scenario job %s queued for %s %s.", key[:12], analysis_id, source_id)

            return 202, self._job_state(job)

    # -- Worker ------------------------------------------------------------------

    async def _work(self) -> None:

        while True:

            while not self.pending:
                self._wake.clear()
                await self._wake.wait()

            job = self.pending.popleft()
            self.current = job
            job.status = "running"
            job.started = time.monotonic()

            try:
                error = await self._run(job)

            except asyncio.CancelledError:
                self._finish(job, "Generation stopped because the server shut down.")
                raise

            except Exception:
                log.exception("Scenario job %s failed unexpectedly.", job.key[:12])
                error = "Generation failed unexpectedly. See the server log."

            self._finish(job, error)

    def _on_stage(self, job: Job) -> Callable[[str], None]:

        def seen(stage: str) -> None:
            self.status.stage = stage
            self.status.stage_at = time.monotonic()

            if stage not in RUNNING_STAGES:
                job.status = "warming_up"

        return seen

    def _on_submitted(self, job: Job) -> Callable[[], None]:

        def submitted() -> None:
            job.status = "running"

        return submitted

    async def _run(self, job: Job) -> str | None:
        """Generate, validate and cache one job. Returns an error message or None."""

        max_new_tokens = job.provenance["generation_config"]["max_new_tokens"]

        try:
            await self.space.ensure_running(self._on_stage(job))
            job.status = "running"
            response = await self.space.generate(
                job.prompt, max_new_tokens, self._on_submitted(job)
            )

        except GenerationTimeout as error:
            log.warning("Scenario job %s timed out.", job.key[:12])
            return str(error)

        except SpaceError as error:
            log.warning("Scenario job %s failed: %s", job.key[:12], error)

            if "quota" in str(error).lower():
                self.status.checked = None

            return str(error)

        try:
            contract.validate_result(response, job.provenance)
            entry = contract.make_cache_entry(
                prompt=job.prompt,
                provenance=job.provenance,
                response=response,
                source="live",
                prompt_version=job.prompt_version
            )

        except contract.ScenarioContractError as error:
            message = self.space.redact(str(error))
            log.warning("Scenario job %s rejected: %s", job.key[:12], message)
            return (
                "The model Space answered, but its result was rejected and not saved: %s"
                % message
            )

        root = self.settings.cache_dir

        await asyncio.to_thread(cache.merge_entry, root, entry)

        for analysis_id, source_id in job.targets:
            await asyncio.to_thread(
                cache.link, root, analysis_id, source_id, job.key, replace=True
            )

        log.info(
            "Scenario job %s done: %s new tokens in %ss.",
            job.key[:12], response["new_tokens"], response["seconds"]
        )

        return None

    def _finish(self, job: Job, error: str | None) -> None:

        self.jobs.pop(job.key, None)

        if self.current is job:
            self.current = None

        for target in job.targets:

            if self.by_path.get(target) is job:
                del self.by_path[target]

            if error is None:
                self.finished[target] = job.key
                self.failed.pop(target, None)

            else:
                self.failed[target] = error

    # -- Health ------------------------------------------------------------------

    def health(self) -> dict[str, Any]:
        """The Health fields for the Space. Never waits on Hugging Face.

        A stale snapshot starts one background refresh; this answer uses the
        snapshot as it is.
        """

        if self.space is not None and self._stale():
            self._refresh = asyncio.get_running_loop().create_task(
                self._refresh_status(), name="space-status"
            )

        snapshot = self.status

        return {
            "space_configured": self.settings.space_configured,
            "space_stage": snapshot.stage,
            "model_unavailable_reason": self.unavailable_reason(),
            "gpu_quota_remaining_s": snapshot.quota.remaining_s,
            "gpu_quota_resets_at": snapshot.quota.resets_at,
            # Stays null until throughput and quota use have been measured.
            "est_generations_left": None
        }

    def unavailable_reason(self) -> str | None:
        """Why POST cannot start live generation now, or None."""

        if self.config_problem or self.space is None:
            return self.config_problem or "Live generation is off."

        if self.status.stage is not None:
            problem = stage_problem(self.status.stage)

            if problem:
                return problem

        if self.status.quota.exhausted():
            return quota_message(self.status.quota)

        return None

    def _stale(self) -> bool:

        if self._refresh is not None and not self._refresh.done():
            return False

        checked = self.status.checked

        return checked is None or time.monotonic() - checked >= self.settings.space_status_ttl_s

    async def _refresh_status(self) -> None:
        """Read the stage (never restarting) and the quota, each bounded."""

        self.status.checked = time.monotonic()

        try:
            self.status.stage = await self.space.runtime_stage()
            self.status.stage_at = time.monotonic()

        except SpaceError as error:
            log.info("Model Space stage unknown: %s", error)
            self.status.stage = None
            self.status.stage_at = None

        self.status.quota = await self.space.quota()


MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun",
          "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def format_reset(moment: datetime) -> str:
    """A reset time for people, in UTC: "25 Oct 2026, 11:00 UTC". A naive time
    is taken as UTC. Locale-independent."""

    if moment.tzinfo is None:
        moment = moment.replace(tzinfo=timezone.utc)

    moment = moment.astimezone(timezone.utc)

    return "%d %s %d, %02d:%02d UTC" % (
        moment.day, MONTHS[moment.month - 1], moment.year, moment.hour, moment.minute
    )


def quota_message(quota: Quota) -> str:

    message = "The ZeroGPU quota for this Hugging Face account is used up"

    if quota.resets_at is not None:
        return "%s until %s." % (message, format_reset(quota.resets_at))

    return message + "."


