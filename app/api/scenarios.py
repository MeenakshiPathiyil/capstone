router = APIRouter(prefix="/api/analyses", tags=["scenarios"])


def errors(*codes):
    return {
        code: {"model": schemas.ErrorResponse, "description": "Error"}
        for code in codes
    }


def scenarios(request: Request) -> ScenarioService:
    return request.app.state.scenarios


@router.get(
    "/{analysis_id}/paths/{source_id}/scenario",
    response_model=schemas.ScenarioState,
    responses=errors(404, 409, 422)
)
async def get_scenario(request: Request, analysis_id: str, source_id: str):
    """The path's scenario state: idle, queued, warming_up, running, done, cached
    or failed. Poll it while the status is queued, warming_up or running."""

    return await scenarios(request).get(analysis_id, source_id)


@router.post(
    "/{analysis_id}/paths/{source_id}/scenario",
    response_model=schemas.ScenarioState,
    responses={
        202: {"model": schemas.ScenarioState, "description": "A job is queued or running"},
        **errors(404, 409, 422, 429, 503)
    }
)
async def request_scenario(
    request: Request,
    response: Response,
    analysis_id: str,
    source_id: str
):
    """Serve the cached scenario (200) or start or join a live generation (202).

    After a failure, POST again to start a new job; nothing is retried
    automatically. 503 when live generation is unavailable and nothing is
    cached. Retry-After is sent only when waiting can help (queue full, quota
    exhausted, with the time to the reset when known); not when live generation
    is not configured or the Space is paused or broken. 429, with Retry-After,
    when this client has started too many live generations recently.
    """

    status, state = await scenarios(request).request(
        analysis_id, source_id, admission(request, "scenarios")
    )

    response.status_code = status

    return state
